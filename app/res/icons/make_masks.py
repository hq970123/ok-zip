# Renders the Lucide (https://lucide.dev, ISC license) SVGs in ./svg into 8-bit
# coverage masks that the app tints at runtime (white on the blue toolbar,
# dark grey on the start page). Output: masks.bin + ../../src/win/icons_gen.rs.
# Requires: pip install resvg-py pillow
import io, os
import resvg_py
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ICONS = {
    "open": "folder-open", "extract": "package-open", "new": "file-archive",
    "add": "file-plus", "delete": "file-minus", "test": "shield-check",
    "view": "eye", "settings": "settings", "home_open": "file-input",
    "home_new": "file-archive", "chevron": "chevron-down",
}
SIZES = [12, 16, 20, 24, 28, 32, 36, 40, 45, 48, 54, 60, 64, 72, 96]

blob = bytearray()
rows = []
for key, svg in ICONS.items():
    src = open(os.path.join(HERE, "svg", svg + ".svg"), encoding="utf-8").read()
    for px in SIZES:
        sw = 2 if px < 28 else 1.5
        if key == "chevron":
            sw = 2.25
        s = src.replace('stroke-width="2"', f'stroke-width="{sw}"').replace("currentColor", "#000")
        png = resvg_py.svg_to_bytes(svg_string=s, width=px, height=px)
        im = Image.open(io.BytesIO(bytes(png))).convert("RGBA")
        assert im.size == (px, px), (key, px, im.size)
        a = im.getchannel("A").tobytes()
        rows.append((key, px, len(blob)))
        blob += a
open(os.path.join(HERE, "masks.bin"), "wb").write(blob)
with open(os.path.join(HERE, "..", "..", "src", "win", "icons_gen.rs"), "w", encoding="utf-8") as f:
    f.write("// @generated by app/res/icons/make_masks.py - do not edit.\n")
    f.write("// Lucide icons (ISC license, https://lucide.dev) as 8-bit coverage masks.\n")
    f.write("pub static MASKS: &[u8] = include_bytes!(\"../../res/icons/masks.bin\");\n")
    f.write("/// (name, size in px, byte offset into MASKS); each mask is size*size bytes.\n")
    f.write("pub static TABLE: &[(&str, u32, usize)] = &[\n")
    for k, px, off in rows:
        f.write(f"    (\"{k}\", {px}, {off}),\n")
    f.write("];\n")
print(len(blob), "bytes")
